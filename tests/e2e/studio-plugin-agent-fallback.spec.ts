import { test, expect } from '@playwright/test'
import { resolve } from 'node:path'

test('renders the same solid initial avatar in historical messages and tasks after plugin removal and reload', async ({ page }, testInfo) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await page.routeWebSocket('**/socket.io/**', () => {})
  await page.route(url => url.pathname.startsWith('/api/'), route => route.fulfill({ json: {} }))
  const entry = '/@fs/' + resolve('tests/e2e/fixtures/plugin-agent-fallback.ts').replace(/^\//, '')
  await page.route('**/__plugin_fallback__*', route => route.fulfill({ contentType: 'text/html', body: `<div id="app"></div><script type="module" src="${entry}"></script>` }))
  await page.goto('/__plugin_fallback__')
  const message = page.getByTestId('messages').locator('img.msg-avatar')
  const task = page.getByTestId('tasks').locator('img')
  await expect(message).toHaveAttribute('alt', 'Oh My Pi')
  await page.getByRole('button', { name: '移除 Agent' }).click()
  await expect(message).toHaveAttribute('alt', 'plugin:omp/omp')
  const src = await message.getAttribute('src')
  expect(decodeURIComponent(src!)).toContain('>P</text>')
  expect(decodeURIComponent(src!)).toContain('<rect ')
  await expect(task).toHaveAttribute('src', src!)
  await expect.poll(() => message.evaluate(img => (img as HTMLImageElement).naturalWidth)).toBe(64)
  await expect.poll(() => page.locator('.history-message-list-shell').evaluate(el => Number(getComputedStyle(el).opacity))).toBe(1)
  await page.screenshot({ path: testInfo.outputPath('agent-initial-light.png') })
  await page.goto('/__plugin_fallback__?removed=1')
  await expect(message).toHaveAttribute('src', src!)
  await expect(task).toHaveAttribute('src', src!)
  await page.evaluate(() => (window as any).avatarFixture.dark())
  await expect(page.locator('html')).toHaveClass(/dark/)
  await expect.poll(() => page.locator('.history-message-list-shell').evaluate(el => Number(getComputedStyle(el).opacity))).toBe(1)
  await page.screenshot({ path: testInfo.outputPath('agent-initial-dark.png') })
  expect(errors).toEqual([])
})
