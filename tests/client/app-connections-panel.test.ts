    expect(source).toContain("t('connections.app.purchaseAccess')")
    expect(source).toContain('QRCode.toDataURL(requestedUrl')
    expect(source).toContain('class="download-tag-qr"')
    expect(source).toContain('<div v-if="androidDownloadUrl" class="download-tag-qr">')
    expect(source).toContain('<div v-if="googlePlayDownloadUrl" class="download-tag-qr">')
    expect(source).toContain('<div v-if="appleDownloadUrl" class="download-tag-qr">')
    expect(source).toContain('downloadQrCodeDataUrls.googlePlay')
    expect(source).toContain('downloadQrCodeDataUrls.apple')
    expect(source).not.toContain('downloadQrCodeDataUrls.harmony')
    expect(source).toContain("t('connections.app.testVersion')")
    expect(source).toContain('class="download-test-status"')
    expect(source).toContain('&:only-child')
    expect(source).toContain('grid-column: 1 / -1')
    expect(source).not.toContain('<NPopover')
    expect(source).toContain('position: absolute')
    expect(source).toContain('width: 112px')
    expect(source).not.toContain('class="app-download-qr-panel"')
    expect(source).toContain('releases/download/v1.0.0/Ekko Studio.apk')
    expect(source).toContain('https://download.ekkolearnai.com/v1.0.0/Ekko Studio.apk')
    expect(source).toContain(':href="androidDownloadUrl"')
    expect(source).toContain('aria-label="GitHub / Cloudflare"')
    expect(source).toContain("t('connections.app.downloadApk')")
    expect(source).toContain('data-platform-icon="google-play"')
    expect(source).toContain('<h4>Android APK</h4>')
    expect(source).toContain('<h4>Android APK</h4>\n              <p>Android</p>')
    expect(source).toContain('<h4>Google Play</h4>')
    expect(source).toContain('<h4>Apple</h4>')
    expect(source).not.toContain('<h4>HarmonyOS</h4>')
